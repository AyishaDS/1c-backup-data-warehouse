


INSERT INTO FCT.SALES
(
    RECORDER_RREF,
    SALE_DATE,
    DEPARTMENT_KEY,
    CLIENT_KEY,
    EMPLOYEE_KEY,
    ITEM_KEY,
    AMOUNT,
    QUANTITY,
    PAYMENT_DOC_RREF
)
SELECT
    A._RecorderRRef,
    DATEADD(YEAR, -Y.Offset, A._Period),
    ISNULL(D.DEPARTMENT_KEY, -1)   AS DEPARTMENT_KEY,
    ISNULL(C.CLIENT_KEY,     -1)   AS CLIENT_KEY,
    ISNULL(E.EMPLOYEE_KEY,   -1)   AS EMPLOYEE_KEY,
    ISNULL(I.ITEM_KEY,       -1)   AS ITEM_KEY,
    A._Fld0027,
    A._Fld0028,
    NULLIF(A._Fld0025_RRRef, 0x00000000000000000000000000000000)
FROM SourceDB.dbo._AccumRg_A A
CROSS JOIN SourceDB.dbo._YearOffset Y
LEFT JOIN DIM.DEPARTMENT D  ON D.DEPARTMENT_RREF  = A._Fld0021RRef
LEFT JOIN DIM.CLIENT C      ON C.CLIENT_RREF      = A._Fld0022RRef
LEFT JOIN DIM.EMPLOYEE E    ON E.EMPLOYEE_RREF    = A._Fld0024RRef
LEFT JOIN DIM.ITEM I        ON I.ITEM_RREF        = A._Fld0026RRef
WHERE A._RecordKind = 0 AND A._RecorderTRef = 0x00000001

